console.log("Arreglos en JavaScript");

/* Los arreglos son como una lista de elementos que pueden ser de cualquier tipo de dato, como números, cadenas de texto, objetos, etc. En JavaScript, los arreglos se crean utilizando corchetes [] y los elementos se separan por comas. */

let videojuegos = ["Super Mario Bros", "Minecraft", "Call of Duty"];

console.log(videojuegos);

console.log("El primer videojuego es: " + videojuegos[0]);

